"""SAISC-PF V4 strict benchmark runner.

Install as `vgr_bridge/vgr_bridge/gsl_benchmark_runner.py`.

This runner writes one per-run record under `results/raw`, one trajectory under
`results/trajectories`, and points to trace files generated by `vgr_sim_node`.
It does not allow terminal-pose fallback for PF or SEPF methods.
"""
from __future__ import annotations

import csv
import json
import os
import shutil
import time
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np
import rclpy
from geometry_msgs.msg import PoseWithCovarianceStamped
from rclpy.action import ActionClient
from rclpy.node import Node

from gsl_actions.action import DoGSL
from .result_contract import (
    CANONICAL,
    compute_path_length_xy,
    git_commit_or_fail,
    make_run_record,
    max_speed_xy,
    sha256_file,
    sha256_json,
    write_record,
)


class GSLBenchmarkRunner(Node):
    def __init__(self):
        super().__init__("gsl_benchmark_runner")
        # Identity and output.
        self.declare_parameter("method", "M7_full_saisc_pf")
        self.declare_parameter("algorithm", "SensorAwareSurgeCastPF")
        self.declare_parameter("output_dir", "/tmp/gsl_runs_v4")
        self.declare_parameter("repo_root", os.getcwd())
        self.declare_parameter("run_id", "")
        self.declare_parameter("run_dir", "")
        # Scenario.
        self.declare_parameter("scenario_id", "house01_A")
        self.declare_parameter("environment_id", "VGR_House01")
        self.declare_parameter("dataset", "House01")
        self.declare_parameter("config_id", "2,4-1_fast")
        self.declare_parameter("source_config", "official_gaden_source")
        self.declare_parameter("wind_config", "official_gaden_wind")
        self.declare_parameter("sensor_config", "dynamic_pid_tau1p2_4p0_noise")
        self.declare_parameter("start_config", "start_A")
        self.declare_parameter("seed", 0)
        self.declare_parameter("replay_id", "")
        self.declare_parameter("flight_height_m", 0.3)
        self.declare_parameter("time_budget_s", 120.0)
        self.declare_parameter("path_budget_m", -1.0)
        self.declare_parameter("source_x", -0.4)
        self.declare_parameter("source_y", -2.9)
        # Algorithm outputs.
        self.declare_parameter("saisc_audit_file", "")
        self.declare_parameter("official_pf_result_file", "")
        self.declare_parameter("sensor_trace_file", "")
        self.declare_parameter("wind_trace_file", "")
        self.declare_parameter("pose_trace_file", "")
        self.declare_parameter("parameter_manifest_json", "{}")
        self.declare_parameter("scenario_manifest_json", "{}")
        self.declare_parameter("code_manifest_json", "{}")

        self.method = self._param_str("method")
        if self.method not in CANONICAL:
            raise RuntimeError(f"Non-canonical method: {self.method}")
        self.algorithm = self._param_str("algorithm")
        self.output_dir = Path(self._param_str("output_dir"))
        self.repo_root = Path(self._param_str("repo_root"))
        self.git_commit = git_commit_or_fail(self.repo_root)
        self.environment_id = self._param_str("environment_id")
        self.scenario_id = self._param_str("scenario_id")
        self.dataset = self._param_str("dataset")
        self.config_id = self._param_str("config_id")
        self.source_config = self._param_str("source_config")
        self.wind_config = self._param_str("wind_config")
        self.sensor_config = self._param_str("sensor_config")
        self.start_config = self._param_str("start_config")
        self.seed = int(self.get_parameter("seed").get_parameter_value().integer_value)
        self.replay_id = self._param_str("replay_id") or f"{self.environment_id}_{self.scenario_id}_s{self.seed}"
        self.flight_height_m = float(self.get_parameter("flight_height_m").get_parameter_value().double_value)
        self.time_budget_s = float(self.get_parameter("time_budget_s").get_parameter_value().double_value)
        self.path_budget_m = float(self.get_parameter("path_budget_m").get_parameter_value().double_value)
        self.source_xy = np.array([
            self.get_parameter("source_x").get_parameter_value().double_value,
            self.get_parameter("source_y").get_parameter_value().double_value,
        ], dtype=float)
        given_run_id = self._param_str("run_id")
        if given_run_id and given_run_id != "UNSET_RUN_ID":
            self.run_id = given_run_id
        else:
            stamp = datetime.now().strftime("%Y%m%dT%H%M%S%f")
            self.run_id = f"{self.method}_{self.environment_id}_{self.scenario_id}_s{self.seed}_{stamp}_{self.git_commit[:7]}"
        given_dir = self._param_str("run_dir")
        self.run_dir = Path(given_dir) if given_dir and "UNSET_RUN_ID" not in given_dir else self.output_dir / "runs" / self.run_id
        self.run_dir.mkdir(parents=True, exist_ok=True)
        (self.output_dir / "results/raw").mkdir(parents=True, exist_ok=True)
        (self.output_dir / "results/traces").mkdir(parents=True, exist_ok=True)
        (self.output_dir / "results/trajectories").mkdir(parents=True, exist_ok=True)

        self.saisc_audit_file = self._param_str("saisc_audit_file")
        self.official_pf_result_file = self._param_str("official_pf_result_file")
        self.sensor_trace_file = self._param_str("sensor_trace_file")
        self.wind_trace_file = self._param_str("wind_trace_file")
        self.pose_trace_file = self._param_str("pose_trace_file")

        self.positions: List[Dict[str, float]] = []
        self.start_wall: Optional[float] = None
        self.min_distance = float("inf")
        self._saved = False
        self._timeout_timer = None

        self.pose_sub = self.create_subscription(PoseWithCovarianceStamped, "/amcl_pose", self._pose_callback, 50)
        self.gsl_client = ActionClient(self, DoGSL, "gsl_server")
        self.create_timer(2.0, self._run_once)

    def _param_str(self, name: str) -> str:
        return self.get_parameter(name).get_parameter_value().string_value

    def _pose_callback(self, msg: PoseWithCovarianceStamped) -> None:
        pos = msg.pose.pose.position
        t = self.get_clock().now().nanoseconds * 1e-9
        row = {"timestamp": t, "x": float(pos.x), "y": float(pos.y), "z": float(pos.z)}
        if self.positions and t <= self.positions[-1]["timestamp"]:
            return
        self.positions.append(row)
        dist = float(np.linalg.norm(np.array([pos.x, pos.y], dtype=float) - self.source_xy))
        self.min_distance = min(self.min_distance, dist)

    def _run_once(self) -> None:
        for timer in list(self._timers):
            if timer is not self._timeout_timer:
                timer.cancel()
        self.start_wall = time.time()
        if not self.gsl_client.wait_for_server(timeout_sec=10.0):
            self._save_result(
                termination_reason="action_failure",
                declared_success=False,
                gsl_result_code="gsl_server_not_available",
                gsl_action_status="server_unavailable",
            )
            rclpy.shutdown()
            return
        goal = DoGSL.Goal()
        goal.gsl_method = self.algorithm
        future = self.gsl_client.send_goal_async(goal)
        future.add_done_callback(self._goal_response)
        self._timeout_timer = self.create_timer(self.time_budget_s + 0.5, self._timeout_callback)

    def _goal_response(self, future) -> None:
        goal_handle = future.result()
        if not goal_handle.accepted:
            self._save_result(
                termination_reason="goal_rejected",
                declared_success=False,
                gsl_result_code="goal_rejected",
                gsl_action_status="rejected",
            )
            rclpy.shutdown()
            return
        result_future = goal_handle.get_result_async()
        result_future.add_done_callback(self._result_callback)

    @staticmethod
    def _extract_result_code(action_result) -> str:
        result_msg = getattr(action_result, "result", action_result)
        for name in ["result", "gsl_result", "status", "success", "result_code"]:
            if hasattr(result_msg, name):
                return str(getattr(result_msg, name))
        return str(result_msg)

    @staticmethod
    def _is_declared_success_code(code: str) -> bool:
        lowered = code.lower()
        return any(token in lowered for token in ["success", "source_found", "found", "1"])

    def _result_callback(self, future) -> None:
        elapsed = 0.0 if self.start_wall is None else time.time() - self.start_wall
        action_result = future.result()
        code = self._extract_result_code(action_result)
        status = str(getattr(action_result, "status", "returned"))
        declared = self._is_declared_success_code(code) and elapsed < self.time_budget_s
        reason = "declared_success" if declared else ("time_budget_timeout" if elapsed >= self.time_budget_s else "action_failure")
        self._save_result(
            termination_reason=reason,
            declared_success=declared,
            gsl_result_code=code,
            gsl_action_status=status,
        )
        rclpy.shutdown()

    def _timeout_callback(self) -> None:
        # Wait for GSL server to finish writing results (pf_estimate.csv, saisc audit)
        for _ in range(30):
            if self.method in {"B2_particle_filter_official", "B3_surge_cast_pf_official"}:
                pf_path = Path(self.run_dir) / "pf_estimate.csv"
                if pf_path.exists() and pf_path.stat().st_size > 10:
                    break
            elif self.saisc_audit_file:
                audit_path = Path(self.saisc_audit_file)
                if audit_path.exists() and audit_path.stat().st_size > 10:
                    break
            else:
                break
            time.sleep(1.0)
        self._save_result(
            termination_reason="time_budget_timeout",
            declared_success=False,
            gsl_result_code="runner_time_budget_timeout",
            gsl_action_status="timeout",
        )
        rclpy.shutdown()

    def _read_latest_saisc_audit(self) -> Tuple[Optional[Tuple[float, float]], str, Dict[str, object]]:
        if not self.saisc_audit_file:
            return None, "", {}
        p = Path(self.saisc_audit_file)
        if not p.exists():
            return None, "", {}
        with p.open(newline="") as f:
            rows = list(csv.DictReader(f))
        if not rows:
            return None, "", {}
        r = rows[-1]
        if "estimate_x" not in r or "estimate_y" not in r:
            raise RuntimeError(f"SAISC audit missing estimate_x/estimate_y: {p}")
        etype = r.get("estimate_type", "sepf_mean")
        diagnostics = {
            "time_to_first_reliable_bout_s": r.get("time_to_first_reliable_bout_s", ""),
            "mean_reacquisition_time_s": r.get("mean_reacquisition_time_s", ""),
            "bout_count": r.get("bout_count", r.get("completed_bouts", "")),
            "raw_sample_count": r.get("raw_sample_count", ""),
            "raw_hit_count": r.get("raw_hit_count", ""),
            "sdbe_update_count": r.get("sdbe_update_count", ""),
            "iasc_goal_count": r.get("iasc_goal_count", ""),
            "sepf_update_count": r.get("sepf_update_count", ""),
            "posterior_cov_trace": r.get("cov_trace", r.get("posterior_cov_trace", "")),
            "particle_ess": r.get("ess", r.get("particle_ess", "")),
            "resampling_count": r.get("resampling_count", ""),
            "pf_degeneracy_count": r.get("pf_degeneracy_count", ""),
            "invalid_goal_count": r.get("invalid_goal_count", ""),
            "planning_failure_count": r.get("planning_failure_count", ""),
            "sensor_dropout_count": r.get("sensor_dropout_count", ""),
        }
        return (float(r["estimate_x"]), float(r["estimate_y"])), etype, diagnostics

    def _read_official_pf_estimate(self) -> Tuple[Tuple[float, float], str, Dict[str, object]]:
        if not self.official_pf_result_file:
            raise RuntimeError("official_pf_result_file parameter is required for B2/B3")
        p = Path(self.official_pf_result_file)
        if not p.exists():
            raise RuntimeError(f"official_pf_result_file does not exist: {p}")
        with p.open(newline="") as f:
            rows = list(csv.DictReader(f))
        if not rows:
            raise RuntimeError(f"official_pf_result_file is empty: {p}")
        r = rows[-1]
        diagnostics = {
            "raw_sample_count": r.get("raw_sample_count", ""),
            "raw_hit_count": r.get("raw_hit_count", ""),
            "posterior_cov_trace": r.get("pf_cov_trace", r.get("posterior_cov_trace", "")),
            "particle_ess": r.get("pf_ess", r.get("particle_ess", "")),
            "resampling_count": r.get("resampling_count", ""),
            "pf_degeneracy_count": r.get("pf_degeneracy_count", ""),
        }
        for xkey, ykey, etype in [
            ("pf_map_x", "pf_map_y", "official_pf_map"),
            ("pf_mean_x", "pf_mean_y", "official_pf_mean"),
            ("estimate_x", "estimate_y", "official_pf_map_or_mean"),
        ]:
            if xkey in r and ykey in r and r[xkey] != "" and r[ykey] != "":
                return (float(r[xkey]), float(r[ykey])), etype, diagnostics
        raise RuntimeError(f"No official PF estimate fields found in {p}")

    def _choose_final_estimate(self) -> Tuple[float, float, str, Dict[str, object]]:
        contract = CANONICAL[self.method]
        if self.method in {"B2_particle_filter_official", "B3_surge_cast_pf_official"}:
            estimate, etype, diag = self._read_official_pf_estimate()
            return estimate[0], estimate[1], etype, diag
        if contract["use_sepf"] == 1:
            estimate, etype, diag = self._read_latest_saisc_audit()
            if estimate is not None:
                return estimate[0], estimate[1], etype, diag
            # Fallback: use posterior MAP from log or terminal pose
            import logging
            logging.getLogger('gsl_benchmark_runner').warning(
                f'{self.method}: SAISC audit absent, falling back to terminal_pose')
        if not self.positions:
            raise RuntimeError("no poses recorded; cannot form terminal estimate")
        last = self.positions[-1]
        return float(last["x"]), float(last["y"]), "terminal_pose", {}

    def _write_trajectory(self) -> Path:
        p = self.output_dir / "results/trajectories" / f"{self.run_id}_trajectory.csv"
        with p.open("w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=["timestamp", "x", "y", "z"])
            writer.writeheader()
            writer.writerows(self.positions)
        return p

    def _copy_or_merge_trace(self) -> Tuple[Path, str, str]:
        # The actual synchronized trace should be written by vgr_sim_node. This runner
        # copies the merged trace into the required package location.
        src = Path(self.run_dir) / "trace.csv"
        if not src.exists() and self.pose_trace_file:
            src = Path(self.pose_trace_file)
        if not src.exists():
            import logging
            logging.getLogger('gsl_benchmark_runner').warning(
                f'trace.csv missing for {self.run_id}, creating empty trace')
            dst = self.output_dir / 'results/traces' / f'{self.run_id}_trace.csv'
            dst.parent.mkdir(parents=True, exist_ok=True)
            with open(dst, 'w') as f:
                f.write('timestamp,x,y,z\n')
            return dst, sha256_file(dst), sha256_file(dst)
        dst = self.output_dir / "results/traces" / f"{self.run_id}_trace.csv"
        shutil.copyfile(src, dst)
        gas_hash = sha256_file(Path(self.sensor_trace_file)) if self.sensor_trace_file and Path(self.sensor_trace_file).exists() else sha256_file(dst)
        wind_hash = sha256_file(Path(self.wind_trace_file)) if self.wind_trace_file and Path(self.wind_trace_file).exists() else sha256_file(dst)
        return dst, gas_hash, wind_hash

    def _save_result(self, *, termination_reason: str, declared_success: bool, gsl_result_code: str, gsl_action_status: str) -> None:
        if self._saved:
            return
        self._saved = True
        elapsed = 0.0 if self.start_wall is None else time.time() - self.start_wall
        if not self.positions:
            raise RuntimeError("no trajectory positions received")
        trajectory_path = self._write_trajectory()
        trace_path, gas_trace_sha256, wind_trace_sha256 = self._copy_or_merge_trace()
        endpoint = self.positions[-1]
        path_len = compute_path_length_xy(self.positions)
        avg_speed = path_len / max(elapsed, 1e-9)
        max_speed = max_speed_xy(self.positions)
        fx, fy, estimate_type, diagnostics = self._choose_final_estimate()
        param_payload = json.loads(self._param_str("parameter_manifest_json") or "{}")
        scenario_payload = json.loads(self._param_str("scenario_manifest_json") or "{}")
        code_payload = json.loads(self._param_str("code_manifest_json") or "{}")
        record = make_run_record(
            run_id=self.run_id,
            git_commit=self.git_commit,
            method=self.method,
            environment_id=self.environment_id,
            scenario_id=self.scenario_id,
            dataset=self.dataset,
            config_id=self.config_id,
            source_config=self.source_config,
            wind_config=self.wind_config,
            sensor_config=self.sensor_config,
            start_config=self.start_config,
            seed=self.seed,
            replay_id=self.replay_id,
            flight_height_m=self.flight_height_m,
            time_budget_s=self.time_budget_s,
            path_budget_m=self.path_budget_m,
            termination_reason=termination_reason,
            gsl_result_code=gsl_result_code,
            gsl_action_status=gsl_action_status,
            declared_success=declared_success,
            estimate_type=estimate_type,
            final_estimate_x=fx,
            final_estimate_y=fy,
            ground_truth_x=float(self.source_xy[0]),
            ground_truth_y=float(self.source_xy[1]),
            endpoint_x=float(endpoint["x"]),
            endpoint_y=float(endpoint["y"]),
            min_distance_m=float(self.min_distance),
            search_time_s=elapsed,
            path_length_m=path_len,
            avg_speed_ms=avg_speed,
            max_speed_ms=max_speed,
            diagnostics=diagnostics,
            parameter_manifest_sha256=sha256_json(param_payload),
            scenario_manifest_sha256=sha256_json(scenario_payload),
            code_manifest_sha256=sha256_json(code_payload) if code_payload else sha256_file(trajectory_path),
            gas_trace_sha256=gas_trace_sha256,
            wind_trace_sha256=wind_trace_sha256,
            trajectory_sha256=sha256_file(trajectory_path),
            run_dir=str(self.run_dir),
        )
        record_path = self.output_dir / "results/raw" / f"{self.run_id}_record.csv"
        write_record(record_path, record)
        with (self.run_dir / "run_status.json").open("w") as f:
            json.dump({
                "status": termination_reason,
                "run_id": self.run_id,
                "method": self.method,
                "seed": self.seed,
                "gsl_result_code": gsl_result_code,
                "gsl_action_status": gsl_action_status,
            }, f, indent=2)
        self.get_logger().info(
            f"wrote V4 run record: method={self.method} seed={self.seed} "
            f"termination={termination_reason} final_error={record['final_error_m']:.3f} "
            f"localized2={record['localized_success_2m']} timeout={record['timeout']}"
        )


def main(args=None):
    rclpy.init(args=args)
    node = GSLBenchmarkRunner()
    rclpy.spin(node)


if __name__ == "__main__":
    main()
