lines = []
lines.append("#!/bin/bash")
lines.append("DIR=/tmp/cp_sbd_exp/eprocess")
lines.append('RESULTS="$DIR/results.csv"')
lines.append('mkdir -p "$DIR"')
lines.append('if [ ! -f "$RESULTS" ]; then')
lines.append('    echo "method,house,seed,max_steps,dist,steps,elapsed,converge_type" > "$RESULTS"')
lines.append("fi")
lines.append("source /opt/ros/humble/setup.bash")
lines.append("source /home/zyc/gsl_ws/install/setup.bash")
lines.append("cd /home/zyc/gsl_ws")
lines.append("LOCKFILE=/tmp/eprocess.lock")
lines.append("acquire_lock() {")
lines.append('    exec 200>"$LOCKFILE"')
lines.append("    if ! flock -n 200; then echo ERROR; exit 1; fi")
lines.append("}")
lines.append("cleanup() {")
lines.append("    killall -9 gsl_actionserver_node vgr_sim_node gsl_benchmark_runner 2>/dev/null || true")
lines.append("    sleep 3")
lines.append("}")
lines.append("run_one() {")
lines.append("    local LABEL=$1 H=$2 CFG=$3 SX=$4 SY=$5 SZ=$6 STX=$7 STY=$8 SEED=$9 MAXSTEPS=${10}")
lines.append('    if grep -q "${LABEL},${H},${SEED},${MAXSTEPS}," "$RESULTS" 2>/dev/null; then')
lines.append('        echo "[SKIP] ${H} ${LABEL} seed=${SEED} steps=${MAXSTEPS}"')
lines.append("        return 0")
lines.append("    fi")
lines.append("    cleanup")
lines.append('    local LOG="$DIR/${LABEL}_${H}_s${SEED}_st${MAXSTEPS}.log"')
lines.append("    local T0=$(date +%s)")
lines.append("    timeout 300 ros2 launch vgr_bridge vgr_ablation.launch.py \\")
lines.append("        vgr_data_path:=/home/zyc/vgr_data_scenarios/$H \\")
lines.append("        config_id:=$CFG algorithm:=OPGSL method:=M7_full_saisc_pf \\")
lines.append("        source_x:=$SX source_y:=$SY source_z:=$SZ \\")
lines.append("        start_x:=$STX start_y:=$STY seed:=$SEED \\")
lines.append("        timeout_sec:=240 use_sbd:=true \\")
lines.append("        opgsl_ddm:=true opgsl_wraig:=true opgsl_cp:=true \\")
lines.append("        opgsl.event_driven.enabled:=true \\")
lines.append("        opgsl.event_driven.eta_fixed:=-1.0 \\")
lines.append("        opgsl.max_steps:=$MAXSTEPS \\")
lines.append('        > "$LOG" 2>&1 || true')
lines.append("    local T1=$(date +%s)")
lines.append('    local ELAPSED=$(( T1 - T0 ))')
lines.append("    sleep 2")
lines.append('    local DIST="NaN" STEPS="0" CTYPE="other"')
lines.append('    local RL=$(grep "OPGSL-SDNBV RESULT:" "$LOG" | tail -1)')
lines.append('    if [ -n "$RL" ]; then')
lines.append('        STEPS=$(echo "$RL" | grep -oP "steps=\\K[0-9]+")')
lines.append('        MX=$(echo "$RL" | grep -oP "posterior_MAP=\\(\\K[-0-9.]+")')
lines.append('        MY=$(echo "$RL" | grep -oP "posterior_MAP=\\([-0-9.]+,\\K[-0-9.]+")')
lines.append('        if [ -n "$MX" ] && [ -n "$MY" ]; then')
lines.append('            DIST=$(python3 -c "import math,sys;a,b,c,d=[float(x) for x in sys.argv[1:5]];r=math.sqrt((a-c)**2+(b-d)**2);print((chr(37)+chr(46)+chr(51)+chr(102))%r)" "$MX" "$MY" "$SX" "$SY" 2>/dev/null)')
lines.append("        fi")
lines.append("    fi")
lines.append('    if grep -q "Found the emission source" "$LOG"; then CTYPE="found"')
lines.append('    elif grep -q "EP-STOP" "$LOG"; then CTYPE="ep_stop"')
lines.append('    elif grep -q "MAXSTEPS-STOP" "$LOG"; then CTYPE="maxsteps"')
lines.append('    elif grep -q "CP-STOP" "$LOG"; then CTYPE="cp_stop"')
lines.append('    elif grep -q "TIMEOUT" "$LOG"; then CTYPE="timeout"')
lines.append('    elif grep -q "Could not find" "$LOG"; then CTYPE="not_found"')
lines.append("    fi")
lines.append('    echo "${LABEL},${H},${SEED},${MAXSTEPS},${DIST},${STEPS},${ELAPSED},${CTYPE}" >> "$RESULTS"')
lines.append('    echo "  -> dist=${DIST} steps=${STEPS} type=${CTYPE} time=${ELAPSED}s"')
lines.append("    cleanup")
lines.append("}")
lines.append("HOUSES=(House01 House02 House03)")
lines.append("CONFIGS=(2,4-1_fast 3,5-1_fast 1-2,5_fast)")
lines.append("SOURCES_X=(-0.40 0.00 -0.45)")
lines.append("SOURCES_Y=(-2.90 -1.00 1.90)")
lines.append("SOURCES_Z=(-0.30 0.20 -0.10)")
lines.append("STARTS_X=(0.30 -0.50 2.00)")
lines.append("STARTS_Y=(-1.20 -2.50 0.00)")
lines.append("acquire_lock")
lines.append('echo "=== E-process Experiment ==="')
lines.append("date")
lines.append("# Fixed step limits: 10, 15, 20, 25, 30, 50, 100")
lines.append("for MAXSTEPS in 10 15 20 25 30 50 100; do")
lines.append("    for h_idx in 0 1 2; do")
lines.append("        H=${HOUSES[$h_idx]}")
lines.append("        for SEED in 0 1 2 3 4; do")
lines.append('            echo "[$H] steps=$MAXSTEPS seed=$SEED"')
lines.append("            date")
lines.append('            run_one "FixedSteps" "$H" "${CONFIGS[$h_idx]}" "${SOURCES_X[$h_idx]}" "${SOURCES_Y[$h_idx]}" "${SOURCES_Z[$h_idx]}" "${STARTS_X[$h_idx]}" "${STARTS_Y[$h_idx]}" "$SEED" "$MAXSTEPS"')
lines.append("        done")
lines.append("    done")
lines.append("done")
lines.append('echo "=== COMPLETE ==="')
lines.append("date")
lines.append('cat "$RESULTS"')
with open("/tmp/eprocess_exp.sh", "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"Written {len(lines)} lines")
