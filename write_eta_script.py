#!/usr/bin/env python3
"""Generate eta ablation serial bash script."""
lines = []
L = lines.append
L("#!/bin/bash")
L("DIR=/tmp/cp_sbd_exp/eta_ablation")
L('RESULTS="$DIR/results.csv"')
L('mkdir -p "$DIR"')
L("")
L('if [ ! -f "$RESULTS" ]; then')
L('    echo "method,house,seed,eta,dist,steps,elapsed,converge_type" > "$RESULTS"')
L("fi")
L("")
L("cd /home/zyc/gsl_ws")
L("source install/setup.bash")
L("")
L("cleanup() {")
L("    killall -9 gsl_actionserver_node vgr_sim_node 2>/dev/null || true")
L("    sleep 3")
L("}")
L("")
L("calc_dist() {")
L('    local MX=$1 MY=$2 SX=$3 SY=$4')
L('    python3 -c "import math,sys;a,b,c,d=[float(x) for x in sys.argv[1:5]];print(chr(37)+chr(46)+chr(51)+chr(102)%(math.sqrt((a-c)**2+(b-d)**2)))" "$MX" "$MY" "$SX" "$SY" 2>/dev/null || echo "NaN"')
L("}")
L("")
L("run_one() {")
L("    local LABEL=$1 H=$2 CFG=$3 SX=$4 SY=$5 SZ=$6 STX=$7 STY=$8 SEED=$9 ETA=${10}")
L('    if grep -q "${LABEL},${H},${SEED}," "$RESULTS" 2>/dev/null; then')
L('        echo "[SKIP] ${H} ${LABEL} seed=${SEED}"')
L("        return 0")
L("    fi")
L("    cleanup")
L('    local LOG="$DIR/${LABEL}_${H}_s${SEED}.log"')
L("    local T0=$(date +%s)")
L("    timeout 300 ros2 launch vgr_bridge vgr_ablation.launch.py \\")
L("        vgr_data_path:=/home/zyc/vgr_data_scenarios/$H \\")
L("        config_id:=$CFG algorithm:=OPGSL method:=M7_full_saisc_pf \\")
L("        source_x:=$SX source_y:=$SY source_z:=$SZ \\")
L("        start_x:=$STX start_y:=$STY seed:=$SEED \\")
L("        timeout_sec:=240 use_sbd:=true \\")
L("        opgsl_ddm:=true opgsl_wraig:=true opgsl_cp:=true \\")
L("        opgsl.event_driven.enabled:=true \\")
L("        opgsl.event_driven.eta_fixed:=$ETA \\")
L('        > "$LOG" 2>&1 || true')
L("    local T1=$(date +%s)")
L('    local ELAPSED=$(( T1 - T0 ))')
L("    sleep 2")
L('    local DIST="NaN" STEPS="0" CTYPE="other"')
L('    local CLEAN=$(sed "s/\\x1b\\[[0-9;]*m//g" "$LOG")')
L('    local RL=$(echo "$CLEAN" | grep "OPGSL-SDNBV RESULT:" | tail -1)')
L('    if [ -n "$RL" ]; then')
L('        STEPS=$(echo "$RL" | grep -oP "steps=\\K[0-9]+")')
L('        MX=$(echo "$RL" | grep -oP "posterior_MAP=\\(\\K[-0-9.]+")')
L('        MY=$(echo "$RL" | grep -oP "posterior_MAP=\\([-0-9.]+,\\K[-0-9.]+")')
L('        if [ -n "$MX" ] && [ -n "$MY" ]; then')
L('            DIST=$(calc_dist "$MX" "$MY" "$SX" "$SY")')
L("        fi")
L("    fi")
L('    if echo "$CLEAN" | grep -q "Found the emission source"; then CTYPE="found"')
L('    elif echo "$CLEAN" | grep -q "EP-STOP"; then CTYPE="ep_stop"')
L('    elif echo "$CLEAN" | grep -q "CP-STOP"; then CTYPE="cp_stop"')
L('    elif echo "$CLEAN" | grep -q "CONVERGED"; then CTYPE="converged"')
L('    elif echo "$CLEAN" | grep -q "Could not find"; then CTYPE="not_found"')
L("    fi")
L('    echo "${LABEL},${H},${SEED},${ETA},${DIST},${STEPS},${ELAPSED},${CTYPE}" >> "$RESULTS"')
L('    echo "  -> dist=${DIST} steps=${STEPS} type=${CTYPE} time=${ELAPSED}s"')
L("    cleanup")
L("}")
L("")
L("HOUSES=(House01 House02 House03)")
L("CONFIGS=(2,4-1_fast 3,5-1_fast 1-2,5_fast)")
L("SOURCES_X=(-0.40 0.00 -0.45)")
L("SOURCES_Y=(-2.90 -1.00 1.90)")
L("SOURCES_Z=(-0.30 0.20 -0.10)")
L("STARTS_X=(0.30 -0.50 2.00)")
L("STARTS_Y=(-1.20 -2.50 0.00)")
L("")
L('echo "=== ETA Ablation Serial ==="')
L("date")
L("")
L("for h_idx in 0 1 2; do")
L("    H=${HOUSES[$h_idx]}")
L("    for ETA in 0.5 0.7 1.0; do")
L("        for SEED in 0 1 2 3 4; do")
L('            echo "[$H] eta=$ETA seed=$SEED"')
L("            date")
L('            run_one "FixedEta_${ETA}" "$H" "${CONFIGS[$h_idx]}" "${SOURCES_X[$h_idx]}" "${SOURCES_Y[$h_idx]}" "${SOURCES_Z[$h_idx]}" "${STARTS_X[$h_idx]}" "${STARTS_Y[$h_idx]}" "$SEED" "$ETA"')
L("        done")
L("    done")
L("done")
L("")
L("for h_idx in 0 1 2; do")
L("    H=${HOUSES[$h_idx]}")
L("    for SEED in 0 1 2 3 4; do")
L('        echo "[$H] adaptive seed=$SEED"')
L("        date")
L('        run_one "Adaptive" "$H" "${CONFIGS[$h_idx]}" "${SOURCES_X[$h_idx]}" "${SOURCES_Y[$h_idx]}" "${SOURCES_Z[$h_idx]}" "${STARTS_X[$h_idx]}" "${STARTS_Y[$h_idx]}" "$SEED" "-1.0"')
L("    done")
L("done")
L("")
L('echo "=== COMPLETE ==="')
L("date")
L('cat "$RESULTS"')
L("")

with open("/tmp/eta_serial.sh", "w", newline="\n") as f:
    f.write("\n".join(lines))
print(f"Written {len(lines)} lines to /tmp/eta_serial.sh")
