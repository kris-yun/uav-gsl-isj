#!/usr/bin/env python3
"""PF-DEI truth-blind run-level source-evidence reference.

This is a mechanism/adequacy diagnostic, not the final runtime posterior.
It deliberately avoids independent per-sample or per-context likelihood factors.
Each candidate source is represented by an ensemble of coherent full-sequence
physical-concentration traces generated by the closed native GADEN forward path.

The diagnostic uses the multivariate energy score on the complete chronological
sequence (or non-overlapping forward-chaining segments).  The time samples are
therefore treated as one correlated object, not as independent replicates.

For the frozen exactly invertible sensor, the normative comparison space is
physical concentration.  A native measured sequence must first be mapped through
the source-proven inverse sensor operator.  Therefore correctly modelled A1
(ideal physical observation) and A2 (native sensor observation canonicalized by
the exact inverse) are required to have source-score parity up to numerical and
serialization tolerances.  A large A1/A2 source-ranking difference is an
implementation/inference-contract failure, not evidence that the sensor destroyed
source information.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Iterable
import math
import numpy as np


@dataclass(frozen=True)
class SegmentResult:
    split_index: int
    train_end: int
    test_end: int
    selected_source: int
    train_selected_score: float
    heldout_selected_score: float
    heldout_null_score: float
    absolute_gain: float
    rival_margin: float
    heldout_rank: int


def _finite_1d(name: str, x) -> np.ndarray:
    a = np.asarray(x, dtype=np.float64)
    if a.ndim != 1 or a.size < 2 or not np.all(np.isfinite(a)):
        raise ValueError(f"{name} must be finite 1-D with >=2 entries")
    return a


def _norm_weights(w, n: int) -> np.ndarray:
    if w is None:
        return np.full(n, 1.0 / n, dtype=np.float64)
    a = np.asarray(w, dtype=np.float64)
    if a.shape != (n,) or np.any(a < 0) or not np.all(np.isfinite(a)) or a.sum() <= 0:
        raise ValueError("invalid weights")
    return a / a.sum()


def sanitize_physical_ppm(x, serialization_bound_ppm: float = 0.0) -> np.ndarray:
    """Enforce physical non-negativity without hiding material inverse errors.

    Tiny negative values within the source-proven deconvolution serialization
    bound are projected to zero.  Values below the negative bound are rejected.
    """
    a = np.asarray(x, dtype=np.float64)
    if not np.all(np.isfinite(a)):
        raise ValueError("non-finite physical concentration")
    if serialization_bound_ppm < 0 or not math.isfinite(serialization_bound_ppm):
        raise ValueError("invalid serialization bound")
    if np.any(a < -serialization_bound_ppm):
        raise ValueError("physical concentration below deconvolution bound")
    return np.maximum(a, 0.0)


def _rms_l2(a: np.ndarray, b: np.ndarray) -> float:
    if a.shape != b.shape or a.ndim != 1 or a.size == 0:
        raise ValueError("distance vectors must have equal non-empty 1-D shape")
    return float(np.linalg.norm(a - b) / math.sqrt(a.size))


def energy_score(observed, ensemble, member_weights=None) -> float:
    """Multivariate energy score; lower is better.

    `observed` is one complete correlated sequence. `ensemble` is [M,T] with one
    coherent simulated trajectory per transport draw.  No temporal independence
    is assumed.
    """
    y = _finite_1d("observed", observed)
    x = np.asarray(ensemble, dtype=np.float64)
    if x.ndim != 2 or x.shape[1] != y.size or x.shape[0] < 2 or not np.all(np.isfinite(x)):
        raise ValueError("ensemble must be finite [M,T] with M>=2")
    w = _norm_weights(member_weights, x.shape[0])

    first = 0.0
    for m in range(x.shape[0]):
        first += float(w[m]) * _rms_l2(x[m], y)

    second = 0.0
    for m in range(x.shape[0]):
        for n in range(x.shape[0]):
            second += float(w[m] * w[n]) * _rms_l2(x[m], x[n])
    return float(first - 0.5 * second)


def source_energy_scores(observed, candidate_ensemble, member_weights=None) -> np.ndarray:
    """Score each source candidate. candidate_ensemble shape [S,M,T]."""
    y = _finite_1d("observed", observed)
    x = np.asarray(candidate_ensemble, dtype=np.float64)
    if x.ndim != 3 or x.shape[2] != y.size or x.shape[0] < 2 or x.shape[1] < 2:
        raise ValueError("candidate_ensemble must be [S,M,T] with S,M>=2")
    return np.asarray([energy_score(y, x[s], member_weights) for s in range(x.shape[0])], dtype=np.float64)


def source_independent_null_score(observed, candidate_ensemble, geometry_prior, member_weights=None) -> float:
    """Energy score of the source-independent prior-predictive mixture.

    The null samples source according to q0 and transport according to the same
    member distribution.  For the finite deterministic ensemble, the exact
    mixture energy score is evaluated with product weights q0[s]*w[m].
    """
    y = _finite_1d("observed", observed)
    x = np.asarray(candidate_ensemble, dtype=np.float64)
    if x.ndim != 3 or x.shape[2] != y.size:
        raise ValueError("candidate_ensemble must be [S,M,T]")
    q0 = _norm_weights(geometry_prior, x.shape[0])
    wm = _norm_weights(member_weights, x.shape[1])
    flat = x.reshape(x.shape[0] * x.shape[1], x.shape[2])
    weights = np.asarray([q0[s] * wm[m] for s in range(x.shape[0]) for m in range(x.shape[1])], dtype=np.float64)
    return energy_score(y, flat, weights)


def equal_forward_boundaries(n: int, folds: int = 5) -> np.ndarray:
    """Deterministic chronological boundaries for blocked forward validation."""
    if n < folds * 4 or folds < 3:
        raise ValueError("sequence too short for requested forward folds")
    b = np.rint(np.linspace(0, n, folds + 1)).astype(int)
    b[0] = 0
    b[-1] = n
    if np.any(np.diff(b) <= 0):
        raise ValueError("degenerate boundaries")
    return b


def blocked_forward_source_transfer(
    observed,
    candidate_ensemble,
    geometry_prior,
    boundaries: Iterable[int] | None = None,
    member_weights=None,
) -> tuple[list[SegmentResult], dict[str, float | int | bool]]:
    """Select source on each growing prefix and score the next disjoint segment.

    This is deliberately run-level/chronological.  It never multiplies isolated
    context likelihoods.  For split k, train is [0,b[k]) and heldout is
    [b[k],b[k+1]).
    """
    y = _finite_1d("observed", observed)
    x = np.asarray(candidate_ensemble, dtype=np.float64)
    if x.ndim != 3 or x.shape[2] != y.size:
        raise ValueError("candidate_ensemble must be [S,M,T]")
    q0 = _norm_weights(geometry_prior, x.shape[0])
    b = equal_forward_boundaries(y.size, 5) if boundaries is None else np.asarray(list(boundaries), dtype=int)
    if b.ndim != 1 or b.size < 4 or b[0] != 0 or b[-1] != y.size or np.any(np.diff(b) <= 0):
        raise ValueError("invalid chronological boundaries")

    rows: list[SegmentResult] = []
    for k in range(1, b.size - 1):
        train = slice(0, int(b[k]))
        test = slice(int(b[k]), int(b[k + 1]))
        train_scores = source_energy_scores(y[train], x[:, :, train], member_weights)
        selected = int(np.argmin(train_scores))
        test_scores = source_energy_scores(y[test], x[:, :, test], member_weights)
        null = source_independent_null_score(y[test], x[:, :, test], q0, member_weights)
        selected_score = float(test_scores[selected])
        rivals = np.delete(test_scores, selected)
        rival_margin = float(np.min(rivals) - selected_score)
        rank = int(1 + np.sum(test_scores < selected_score))
        rows.append(SegmentResult(
            split_index=k,
            train_end=int(b[k]),
            test_end=int(b[k + 1]),
            selected_source=selected,
            train_selected_score=float(train_scores[selected]),
            heldout_selected_score=selected_score,
            heldout_null_score=float(null),
            absolute_gain=float(null - selected_score),
            rival_margin=rival_margin,
            heldout_rank=rank,
        ))

    mean_abs = float(np.mean([r.absolute_gain for r in rows]))
    mean_rival = float(np.mean([r.rival_margin for r in rows]))
    positive_abs = int(sum(r.absolute_gain > 0 for r in rows))
    top1 = int(sum(r.heldout_rank == 1 for r in rows))
    summary = {
        "segments": len(rows),
        "mean_absolute_gain": mean_abs,
        "mean_rival_margin": mean_rival,
        "positive_absolute_segments": positive_abs,
        "heldout_top1_segments": top1,
        "predictive_pass": bool(mean_abs > 0.0 and mean_rival > 0.0),
    }
    return rows, summary


def permutation_check(observed, candidate_ensemble, geometry_prior, permutation) -> float:
    """Return max score mismatch after source permutation/unpermutation."""
    y = _finite_1d("observed", observed)
    x = np.asarray(candidate_ensemble, dtype=np.float64)
    p = np.asarray(permutation, dtype=int)
    if p.shape != (x.shape[0],) or set(p.tolist()) != set(range(x.shape[0])):
        raise ValueError("invalid permutation")
    q0 = _norm_weights(geometry_prior, x.shape[0])
    base = source_energy_scores(y, x)
    perm = source_energy_scores(y, x[p])
    restored = np.empty_like(perm)
    restored[p] = perm
    null0 = source_independent_null_score(y, x, q0)
    null1 = source_independent_null_score(y, x[p], q0[p])
    return float(max(np.max(np.abs(base - restored)), abs(null0 - null1)))
