#!/usr/bin/env python3
"""Truth-independent PF-DEI sensor-history counterfactual diagnostic.

This script does NOT fit a sensor model. It compares two or more synthetic
forward runs generated by the authoritative native sensor path.

Required experimental design:
  * same source and transport realization;
  * same physical concentration sequence during the evaluation window;
  * different pre-evaluation exposure histories;
  * same evaluation timestamps and threshold.

If measured ppm or the block decision differs during an identical physical
concentration suffix, the local-stop observation assumption is falsified and
persistent sensor history is mechanistically active.
"""
from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path
import numpy as np


def load(path: Path):
    with path.open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    req = {
        "scenario_id", "history_id", "phase", "sim_time",
        "physical_concentration_ppm", "measured_gas_ppm", "threshold_gas"
    }
    if not rows or not req.issubset(rows[0]):
        raise ValueError(f"CSV must contain {sorted(req)}")
    forbidden = {"true_source", "localization_error", "final_error", "off_on_improvement"}
    if forbidden.intersection(rows[0]):
        raise ValueError("performance/development-truth columns are forbidden")
    return rows


def analyze(rows, atol_c: float):
    groups = defaultdict(list)
    for r in rows:
        if r["phase"] != "evaluation":
            continue
        groups[(r["scenario_id"], r["history_id"])].append(r)
    by_scenario = defaultdict(dict)
    for (sid, hid), rr in groups.items():
        rr.sort(key=lambda z: float(z["sim_time"]))
        by_scenario[sid][hid] = rr

    out = []
    active = 0
    for sid, histories in sorted(by_scenario.items()):
        if len(histories) < 2:
            raise ValueError(f"scenario {sid}: need >=2 history arms")
        ids = sorted(histories)
        ref = histories[ids[0]]
        t_ref = np.asarray([float(r["sim_time"]) for r in ref])
        c_ref = np.asarray([float(r["physical_concentration_ppm"]) for r in ref])
        th_ref = np.asarray([float(r["threshold_gas"]) for r in ref])
        m_ref = np.asarray([float(r["measured_gas_ppm"]) for r in ref])
        if len(ref) < 2:
            raise ValueError(f"scenario {sid}: evaluation window too short")
        scenario_active = False
        pair_rows = []
        for hid in ids[1:]:
            cur = histories[hid]
            if len(cur) != len(ref):
                raise ValueError(f"scenario {sid}: evaluation lengths differ")
            t = np.asarray([float(r["sim_time"]) for r in cur])
            c = np.asarray([float(r["physical_concentration_ppm"]) for r in cur])
            th = np.asarray([float(r["threshold_gas"]) for r in cur])
            m = np.asarray([float(r["measured_gas_ppm"]) for r in cur])
            if not np.allclose(t, t_ref, rtol=0.0, atol=1e-9):
                raise ValueError(f"scenario {sid}: evaluation timestamps differ")
            if not np.allclose(c, c_ref, rtol=0.0, atol=atol_c):
                raise ValueError(f"scenario {sid}: physical concentration suffix is not identical")
            if not np.allclose(th, th_ref, rtol=0.0, atol=1e-12):
                raise ValueError(f"scenario {sid}: threshold differs")
            delta = m - m_ref
            max_abs = float(np.max(np.abs(delta)))
            mean_abs = float(np.mean(np.abs(delta)))
            ref_hit = bool(float(np.mean(m_ref)) > float(th_ref[0]))
            cur_hit = bool(float(np.mean(m)) > float(th_ref[0]))
            pair_active = bool(max_abs > 1e-12 or ref_hit != cur_hit)
            scenario_active |= pair_active
            pair_rows.append({
                "reference_history": ids[0],
                "comparison_history": hid,
                "max_abs_measured_difference_ppm": max_abs,
                "mean_abs_measured_difference_ppm": mean_abs,
                "reference_block_hit": ref_hit,
                "comparison_block_hit": cur_hit,
                "history_effect_active": pair_active,
            })
        active += int(scenario_active)
        out.append({"scenario_id": sid, "history_effect_active": scenario_active, "comparisons": pair_rows})

    if not out:
        raise ValueError("no evaluation rows")
    return {
        "contract": "PF_DEI_SENSOR_HISTORY_COUNTERFACTUAL_V1",
        "scenarios": len(out),
        "history_effect_active_scenarios": active,
        "local_stop_observation_falsified": bool(active > 0),
        "results": out,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("csv", type=Path)
    ap.add_argument("--physical-concentration-atol", type=float, default=1e-9)
    ap.add_argument("--out-json", type=Path)
    args = ap.parse_args()
    result = analyze(load(args.csv), args.physical_concentration_atol)
    text = json.dumps(result, indent=2)
    if args.out_json:
        args.out_json.parent.mkdir(parents=True, exist_ok=True)
        args.out_json.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
